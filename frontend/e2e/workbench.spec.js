import { test, expect } from '@playwright/test';

test('manual learning flow saves a reflection and switches context without sharing notes', async ({ page }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('heading', { name: /Knowledge,/ })).toBeVisible();
  await page.screenshot({ path: '../.review/ui/studio.png', fullPage: true });
  await page.getByRole('button', { name: 'Preferences', exact: true }).click();
  await page.getByLabel('Manual profile preview').selectOption('DV-STUDENT-01');
  const dialog = page.getByRole('dialog');
  if (await dialog.isVisible()) await page.getByRole('button', { name: 'Discard & switch' }).click();
  await expect(page.getByText('Beginning learner', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Anatomy atlas', exact: true }).click();
  await page.screenshot({ path: '../.review/ui/atlas.png', fullPage: true });
  await page.getByPlaceholder('Search by tooth name or FDI number').fill('unknown tooth');
  await expect(page.getByRole('heading', { name: 'No specimen matches that search.' })).toBeVisible();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.getByRole('button', { name: 'Inspect specimen' }).click();
  await expect(page.getByRole('heading', { name: 'Upper right first molar', exact: true })).toBeVisible();
  await expect(page.locator('canvas')).toBeVisible();
  await page.screenshot({ path: '../.review/ui/workbench.png', fullPage: true });
  const rotation = page.getByRole('slider', { name: 'Turn specimen' });
  await rotation.focus();
  for (let i=0;i<10;i++) await rotation.press('ArrowRight');
  await page.getByRole('button', { name: 'Dentin', exact: true }).click();
  await expect(page.getByText('Dentin lies beneath enamel', { exact: false })).toBeVisible();
  await page.getByLabel('Active tool').selectOption('mirror');
  await page.getByRole('slider', { name: 'Tool horizontal position' }).focus();
  await page.getByRole('slider', { name: 'Tool horizontal position' }).press('ArrowLeft');
  await page.getByRole('button', { name: 'Confirm mirror placement' }).click();
  await page.getByRole('button', { name: 'Pause session' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Resume session' }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.locator('.specimen-stage').getByRole('button', { name: 'Reset view', exact: true }).click();
  await page.getByRole('button', { name: 'Keep working' }).click();
  await page.getByRole('button', { name: 'Finish & review' }).click();
  const note = `Molar reflection ${Date.now()}`;
  await page.getByLabel('Reflect before you move on').fill(note);
  await page.getByRole('button', { name: 'Save reflection' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Reflection saved' })).toBeVisible();
  await page.screenshot({ path: '../.review/ui/review.png', fullPage: true });
  await page.getByRole('button', { name: 'Open journal' }).click();
  await expect(page.getByText(note, { exact: true })).toBeVisible();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByText(note, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Preferences', exact: true }).click();
  await page.getByLabel('Manual profile preview').selectOption('DV-STUDENT-02');
  await expect(page.getByRole('heading', { name: /Knowledge,/ })).toBeVisible();
  await page.getByRole('button', { name: 'Preferences', exact: true }).click();
  await expect(page.getByText('Explore structure and relationships', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Session journal', exact: true }).click();
  await expect(page.getByText(note, { exact: true })).toBeHidden();
  await page.getByRole('button', { name: 'Preferences', exact: true }).click();
  await page.getByLabel('Manual profile preview').selectOption('DV-STUDENT-01');
  await expect(page.getByRole('heading', { name: /Knowledge,/ })).toBeVisible();
  await page.getByRole('button', { name: 'Session journal', exact: true }).click();
  await expect(page.getByText(note, { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('essential navigation fits a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('button', { name: 'Studio', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Studio', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Knowledge,/ })).toBeVisible();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  expect(overflow).toBe(false);
  await page.screenshot({ path: '../.review/ui/mobile-studio.png', fullPage: true });
});
